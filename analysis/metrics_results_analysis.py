def extract_choice(raw):
    """
    Extract model choice from raw_response.
    Valid outputs are: A, B, ABSTAIN.
    Invalid or unparseable outputs return None.
    """
    if pd.isna(raw):
        return None

    text = str(raw).strip()

    # Sometimes raw_response is wrapped in markdown code block
    text = text.replace("```json", "").replace("```", "").strip()

    # Try to parse as JSON
    try:
        data = json.loads(text)
        if isinstance(data, dict):
            choice = data.get("choice", None)
            if choice is not None:
                choice = str(choice).strip().upper()
                if choice in ["A", "B", "ABSTAIN"]:
                    return choice
                else:
                    return None
    except Exception:
        pass

    # Fallback: look for explicit choice pattern
    match = re.search(r'"choice"\s*:\s*"([^"]+)"', text, flags=re.IGNORECASE)
    if match:
        choice = match.group(1).strip().upper()
        if choice in ["A", "B", "ABSTAIN"]:
            return choice
        else:
            return None

    # Fallback for very short direct answers
    cleaned = text.strip().upper()
    if cleaned in ["A", "B", "ABSTAIN"]:
        return cleaned

    return None


