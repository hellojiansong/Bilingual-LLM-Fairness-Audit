def calculate_delta_sr(df):
    total = len(df)
    if total == 0:
        return None

    selected = df["selected_group_clean"]
    p_dutch = (selected == "dutch").sum() / total
    p_minority = (selected == "minority").sum() / total

    return pd.Series({
        "p_select_dutch": p_dutch,
        "p_select_minority": p_minority,
        "delta_sr": p_dutch - p_minority,
        "n": total
    })


